// Build report/index.html (plus report/img/) from the outputs run.sh leaves in this folder.
// Usage: node report.mjs <after checkout>   (the checkout's Earth map files give the byte count)
// The folder it writes is self-contained: open report/index.html in any browser, or copy it away.
import { copyFile, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const after = process.argv[2];
if (!after) throw new Error('usage: node report.mjs <after checkout>');
const out = path.join(here, 'report');
const read = (name) => readFile(path.join(here, name), 'utf8');

const meta = Object.fromEntries((await read('output-meta.txt')).trim().split('\n').map((line) => {
  const [key, ...rest] = line.split(' ');
  return [key, rest.join(' ')];
}));
const startup = {};
for (const line of (await read('output-startup.txt')).split('\n')) {
  const m = line.match(/^(before|after): first picture (\d+) ms \| 30 frames (\d+) ms \| worst frame next 8 s (\d+) ms .*maps ready (\d+) ms/);
  if (m) startup[m[1]] = { first: +m[2], thirty: +m[3], worst: +m[4], maps: +m[5] };
}
if (!startup.before || !startup.after) throw new Error('output-startup.txt has no before/after medians');
const runs = (await read('output-startup.txt')).match(/runs \[/g)?.length ? JSON.parse((await read('output-startup.txt')).match(/runs (\[.*\])/)[1]).length : '?';
const capture = await read('output-capture.txt');
const renderer = capture.match(/^renderer: (.*)$/m)?.[1] ?? 'unknown';
const problems = JSON.parse(capture.match(/^problems: (.*)$/m)?.[1] ?? '[]').concat(
  JSON.parse((await read('output-capture-before.txt')).match(/^problems: (.*)$/m)?.[1] ?? '[]').map((p) => `before: ${p}`));

const surfaces = path.join(after, 'public/textures/surfaces');
let earthBytes = 0;
for (const name of (await readdir(surfaces)).filter((n) => n.startsWith('earth_'))) earthBytes += (await stat(path.join(surfaces, name))).size;

await rm(out, { recursive: true, force: true });
await mkdir(path.join(out, 'img'), { recursive: true });
const shots = [];
for (const [dir, prefix] of [['captures', ''], ['captures-before', 'before-']]) {
  for (const name of (await readdir(path.join(here, dir))).filter((n) => n.endsWith('.png'))) {
    await copyFile(path.join(here, dir, name), path.join(out, 'img', prefix + name));
    shots.push(prefix + name);
  }
}
const img = (name) => {
  if (!shots.includes(`${name}.png`)) throw new Error(`missing capture ${name}.png`);
  return `img/${name}.png`;
};

const s = (ms) => `${(ms / 1000).toFixed(2)} s`;
const delta = (a, b, unit = 's') => {
  const d = b - a;
  return unit === 's' ? `${d >= 0 ? '+' : '−'}${Math.abs(d / 1000).toFixed(1)} s` : `${d >= 0 ? '+' : '−'}${Math.abs(d)} ms`;
};
const mb = (bytes) => `${(bytes / 1e6).toFixed(1)} MB`;
const esc = (text) => String(text).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const { before: b, after: a } = startup;

const figure = (name, label, where, alt, tag = '') => `
      <figure>
        ${tag}
        <img src="${img(name)}" width="928" height="900" alt="${esc(alt)}" loading="lazy">
        <figcaption><span class="label">${label}</span><span class="where">${where}</span></figcaption>
      </figure>`;
const tagBefore = `<span class="tag">Before · ${esc(meta.before)}</span>`;
const tagAfter = `<span class="tag after">After · ${esc(meta.after)}</span>`;
const on = '<span class="tag after">Relief on</span>';
const off = '<span class="tag">Relief off</span>';
