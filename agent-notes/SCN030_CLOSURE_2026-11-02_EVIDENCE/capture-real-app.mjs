import { chromium } from '/tmp/solar-partials-clean-install-20261031/node_modules/playwright/index.mjs';
import AxeBuilder from '/tmp/solar-partials-clean-install-20261031/node_modules/@axe-core/playwright/dist/index.mjs';
import { writeFileSync } from 'node:fs';
const out=new URL('./', import.meta.url).pathname;
const browser=await chromium.launch({channel:'chromium',args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'reduce'});
const page=await context.newPage();
await page.route('**/*',r=>new URL(r.request().url()).origin==='http://127.0.0.1:4193'?r.continue():r.fulfill({status:503,contentType:'application/json',body:'{}',headers:{'Access-Control-Allow-Origin':'*'}}));
await page.goto('http://127.0.0.1:4193/?renderScale=0.5&maxPixelRatio=1');
await page.waitForFunction(()=>document.querySelector('#status-zoom')?.textContent!=='Range · —',null,{timeout:60000});
await page.locator('#camera-tools summary').click();
await page.screenshot({path:out+'actual-app-desktop-final.png'});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:out+'actual-app-mobile-closed-final.png'});
await page.locator('#panel-toggle').click();
await page.screenshot({path:out+'actual-app-mobile-open-final.png'});
await page.keyboard.press('Escape');
const loss=await page.locator('#space-canvas').evaluate(canvas=>{const ext=canvas.getContext('webgl2').getExtension('WEBGL_lose_context');ext?.loseContext();return Boolean(ext);});
await page.locator('#renderer-unavailable').waitFor({state:'visible'});
const recovery=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']).analyze();
await page.screenshot({path:out+'actual-app-recovery-final.png'});
writeFileSync(out+'actual-app-recovery-final-axe.json',JSON.stringify({scope:'real application after actual WEBGL_lose_context',browser:browser.version(),viewport:page.viewportSize(),lossExtension:loss,violations:recovery.violations,incomplete:recovery.incomplete,passes:recovery.passes.map(x=>x.id)},null,2));
console.log(JSON.stringify({loss,violations:recovery.violations.map(x=>x.id),incomplete:recovery.incomplete.map(x=>x.id)}));
await page.evaluate(()=>window.dispatchEvent(new Event('beforeunload')));
await browser.close();
